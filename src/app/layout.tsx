import type { Metadata } from "next";
import type { ReactNode } from "react";
import { IBM_Plex_Mono, IBM_Plex_Sans } from "next/font/google";
import { Header } from "@/components/layout/Header";
import { HeaderVisibility } from "@/components/layout/HeaderVisibility";
import { getImage, portfolio } from "@/lib/portfolio";
import "./globals.css";

const plexSans = IBM_Plex_Sans({
  variable: "--font-sans",
  subsets: ["latin"],
  weight: ["400", "500", "600", "700"],
  display: "swap",
});

const plexMono = IBM_Plex_Mono({
  variable: "--font-mono",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  display: "swap",
});

// ─── Site-wide SEO metadata ──────────────────────────────────────────────────
// Next.js exports this object and injects it into <head> automatically.
// No more manually writing <title> or <meta> tags in HTML files!
export const metadata: Metadata = {
  title: {
    default: portfolio.site.title,
    template: portfolio.site.titleTemplate,
  },
  description: portfolio.site.description,
  openGraph: {
    ...portfolio.site.openGraph,
    siteName: portfolio.site.name,
  },
  icons: {
    icon: [
      { url: getImage(portfolio.site.icons.iconSvg).generatedFile, type: "image/svg+xml" },
      { url: getImage(portfolio.site.icons.iconPng).generatedFile, type: "image/png" },
      { url: getImage(portfolio.site.icons.favicon).generatedFile, sizes: "any" },
    ],
    shortcut: getImage(portfolio.site.icons.favicon).generatedFile,
    apple: getImage(portfolio.site.icons.iconPng).generatedFile,
  },
};

// ─── Root Layout ─────────────────────────────────────────────────────────────
// This component wraps EVERY page on the site. Think of it as your master
// HTML template — the equivalent of copy-pasting a <nav> and <footer> into
// every HTML page, except here you define it once and Next.js handles the rest.
//
// LayoutProps<"/"> is a type auto-generated by Next.js that describes what
// props this layout receives (mainly {children} — the page content).
export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html
      lang="en"
      // We inject the three CSS variable names as classes on <html>.
      // This is how next/font works: it creates scoped CSS variable definitions
      // that are only active when these class names are present on an ancestor.
      className={`${plexSans.variable} ${plexMono.variable} h-full antialiased dark`}
    >
      <body
        className="min-h-full flex flex-col bg-background text-foreground"
      >
        {/* Header lives here in the layout but is hidden in /terminal mode */}
        <HeaderVisibility>
          <Header />
        </HeaderVisibility>
        <main className="flex flex-col flex-1">
          {children}
        </main>
      </body>
    </html>
  );
}
